import { mkdir, writeFile, readFile } from 'node:fs/promises';
import { spawnSync } from 'node:child_process';
import { networkInterfaces } from 'node:os';
import { X509Certificate } from 'node:crypto';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
process.chdir(root);
const dir = path.join(root, '.local-https');
await mkdir(path.join(dir, 'tools'), { recursive: true });
await mkdir(path.join(dir, 'ca'), { recursive: true });
if (process.platform !== 'win32' || process.arch !== 'x64') throw Error('Este configurador es para Windows x64.');
const headers = { 'User-Agent': 'Kalen-local-https', Accept: 'application/vnd.github+json' };
const releaseResponse = await fetch('https://api.github.com/repos/FiloSottile/mkcert/releases/latest', { headers, signal: AbortSignal.timeout(30000) });
if (!releaseResponse.ok) throw Error('No se pudo consultar la descarga oficial de mkcert: ' + releaseResponse.status);
const release = await releaseResponse.json();
const asset = release.assets.find(asset => asset.name.endsWith('-windows-amd64.exe'));
if (!asset) throw Error('No se encontro mkcert para Windows x64.');
const response = await fetch(asset.browser_download_url, { signal: AbortSignal.timeout(60000) });
if (!response.ok) throw Error('No se pudo descargar mkcert: ' + response.status);
const binary = Buffer.from(await response.arrayBuffer());
if (asset.digest?.startsWith('sha256:')) {
  const { createHash } = await import('node:crypto');
  if ('sha256:' + createHash('sha256').update(binary).digest('hex') !== asset.digest) throw Error('La descarga no coincide con su SHA256.');
}
const exe = path.join(dir, 'tools/mkcert.exe');
await writeFile(exe, binary);
const ips = Object.values(networkInterfaces()).flat().filter(address => address?.family === 'IPv4' && !address.internal && !address.address.startsWith('169.254.')).map(address => address.address);
const names = [...new Set(['localhost', '127.0.0.1', '::1', ...ips])];
const result = spawnSync(exe, ['-cert-file', path.join(dir, 'server.pem'), '-key-file', path.join(dir, 'server-key.pem'), ...names], { env: { ...process.env, CAROOT: path.join(dir, 'ca') }, stdio: 'inherit', windowsHide: true });
if (result.error) throw result.error;
if (result.status !== 0) throw Error('No se pudo generar el certificado.');
const ca = await readFile(path.join(dir, 'ca/rootCA.pem'));
await writeFile(path.join(dir, 'Kalen-CA.crt'), ca);
await writeFile(path.join(dir, 'info.json'), JSON.stringify({ mkcert: release.tag_name, names, fingerprint: new X509Certificate(ca).fingerprint256 }, null, 2));
const build = spawnSync(process.execPath, ['node_modules/vite/bin/vite.js', 'build', '--mode', 'lan', '--outDir', path.join(dir, 'dist')], { env: { ...process.env, VITE_SYNC_URL: '' }, stdio: 'inherit', windowsHide: true });
if (build.status !== 0) throw Error('No se pudo compilar la app local.');
const pwa = spawnSync(process.execPath, [path.join(root, 'scripts/build-pwa.mjs')], { cwd: dir, stdio: 'inherit', windowsHide: true });
if (pwa.status !== 0) throw Error('No se pudo preparar la instalacion PWA.');
console.log('HTTPS preparado para: ' + names.join(', '));
console.log('Huella CA: ' + new X509Certificate(ca).fingerprint256);
